// 任務狀態 → 中文顯示（中文優先鐵則 · 單一來源避免各視圖走鐘）
//
// ⚠️⚠️ **DB 存的還是舊字串**（`tickets.confirm_status` = 待確認/待簽核/已簽核/…）。
//    這裡只換顯示。改 DB 值要 migration 改 47 筆資料 ＋ 改十幾處字串比對，
//    漏一處就會有任務永遠卡在某個狀態 —— 風險高很多而沒有對應的好處。
//    所以：**比對一律用 DB 值，顯示一律走這支。**
//
// ── 為什麼改名（2026-08-24 台灣福祉回報）──────────────────────
// 總經理看到「已簽核」旁邊寫「卡住 24 天」，覺得矛盾。
// 實際上任務有**三條軸**，而其中兩條都用了聽起來像「處理完了」的詞：
//
//   軸1 這是不是一件要追的事？   待確認 → 已忽略        （AI 沒把握，人來判斷）
//   軸2 AI 寫的內容對不對？      待簽核 → 已簽核        （主管比對原始對話）
//   軸3 事情做完了沒？           work_status open/closed
//
// 「已簽核 + 24 天沒進度」在邏輯上完全一致（你確認過這件事是真的，但沒人去做），
// 是「簽核」這個詞被讀成「處理完了」。
//
// 改法（2026-08-25 裁定）：**三條軸各用不同的詞，一次拉開**
//   軸1 → 待判定   問的是「要不要追」
//   軸2 → 待核對 / 已核對   「核對」明確指向比對正確性，不含完成意味
//   軸3 → 維持 進行中 / 已完成
//
// ⚠️ 原本提議軸2 改叫「確認」—— 那會跟軸1 現有的「待確認」撞名，是錯的。
// ⚠️ 2026-08-26 i18n：文字搬進 i18n/zh-TW.ts 與 en.ts（key = `confirmStatus.<DB 值>`）。
//    這支保留原本的 API，**caller 一行都不用改** —— 但現在會跟著語言切換。
/** 未知值 fallback 原值 —— 不吞資料，但至少看得出來是沒對應到 */
export const confirmLabel = (s: string | null | undefined): string =>
  s ? t(`confirmStatus.${s}`) : "";
